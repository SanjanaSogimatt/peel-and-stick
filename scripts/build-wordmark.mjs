// Builds the footer wordmark sticker (site/wordmark.ts) from Geist Bold as real paths,
// so it renders identically everywhere, including inside <img> where web fonts don't load.
import opentype from "opentype.js";
import { writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const font = opentype.loadSync(join(root, "scripts", "fonts", "Geist-Bold.ttf"));
const TEXT = "peel & stick";
const SIZE = 220;
const COLORS = ["#ff4f9a", "#ffd43b", "#4d7cff", "#2fd3a0", "#ff7a2f", "#b79cff"];
const TILTS = [-5, 3, -2, 4, 0, -4, 2, -3, 5, -2, 3, -4];
const LIFT = [0, -6, 4, -3, 0, 5, -5, 2, -4, 6, -2, 3];

let x = 0, ci = 0;
const glyphs = [];
for (const [i, ch] of [...TEXT].entries()) {
  const g = font.charToGlyph(ch);
  const adv = (g.advanceWidth / font.unitsPerEm) * SIZE;
  if (ch !== " ") {
    const path = g.getPath(x, 0, SIZE);
    const bb = path.getBoundingBox();
    const cx = (bb.x1 + bb.x2) / 2, cy = (bb.y1 + bb.y2) / 2;
    glyphs.push({ d: path.toPathData(2), t: `translate(0 ${LIFT[i % LIFT.length]}) rotate(${TILTS[i % TILTS.length]} ${cx.toFixed(1)} ${cy.toFixed(1)})`, color: COLORS[ci++ % COLORS.length], bb });
  }
  x += adv - SIZE * 0.012; // a touch tighter than default
}
const minX = Math.min(...glyphs.map((g) => g.bb.x1)), maxX = Math.max(...glyphs.map((g) => g.bb.x2));
const minY = Math.min(...glyphs.map((g) => g.bb.y1)), maxY = Math.max(...glyphs.map((g) => g.bb.y2));
const P = 30; // room for the white die-cut stroke and tilts
const vb = [minX - P, minY - P, maxX - minX + P * 2, maxY - minY + P * 2].map((n) => +n.toFixed(1));

const cut = glyphs.map((g) => `<path d="${g.d}" transform="${g.t}"/>`).join("");
const letters = glyphs.map((g) => `<path d="${g.d}" transform="${g.t}" fill="${g.color}"/>`).join("");
const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${vb.join(" ")}">` +
  `<g fill="#fff" stroke="#fff" stroke-width="40" stroke-linejoin="round">${cut}</g>` +
  `<g stroke="#18161d" stroke-width="5" stroke-linejoin="round" paint-order="stroke">${letters}</g></svg>`;

const src = "data:image/svg+xml," + svg.replace(/"/g, "'").replace(/[\r\n%#()<>?[\\\]^`{|}]/g, encodeURIComponent);
writeFileSync(join(root, "site", "wordmark.ts"),
  `// AUTO-GENERATED by scripts/build-wordmark.mjs\nexport const wordmark = { name: "wordmark", width: ${Math.round(vb[2])}, height: ${Math.round(vb[3])}, src: ${JSON.stringify(src)} };\n`);
writeFileSync(join(root, "site", "wordmark.svg"), svg);
console.log("wordmark", vb, Math.round(src.length / 1024) + "KB");
