// Turns every SVG in /stickers into a typed, tree-shakeable export in src/art/index.ts.
// Run: npm run art   (also runs automatically before `npm run build`)
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { join, basename, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const srcDir = join(root, "stickers");
const outFile = join(root, "src", "art", "index.ts");

const camel = (s) =>
  s.replace(/\.svg$/i, "")
    .replace(/[^a-zA-Z0-9]+(.)?/g, (_, c) => (c ? c.toUpperCase() : ""))
    .replace(/^[0-9]/, (d) => "_" + d)
    .replace(/^./, (c) => c.toLowerCase());

function sizeOf(svg, file) {
  const vb = svg.match(/viewBox\s*=\s*["']\s*[-\d.]+[\s,]+[-\d.]+[\s,]+([\d.]+)[\s,]+([\d.]+)/i);
  if (vb) return [Math.round(+vb[1]), Math.round(+vb[2])];
  const w = svg.match(/\bwidth\s*=\s*["']([\d.]+)/i), h = svg.match(/\bheight\s*=\s*["']([\d.]+)/i);
  if (w && h) return [Math.round(+w[1]), Math.round(+h[1])];
  throw new Error(`${file}: needs a viewBox or width/height`);
}

// Smallest safe data-URI encoding for SVG (works in <img> and CSS mask-image)
const toDataUri = (svg) =>
  "data:image/svg+xml," +
  svg.replace(/<\?xml[^>]*>/, "").replace(/<!--[\s\S]*?-->/g, "")
    .replace(/\s+/g, " ").replace(/>\s+</g, "><").trim()
    .replace(/"/g, "'")
    .replace(/[\r\n%#()<>?[\\\]^`{|}]/g, encodeURIComponent);

const files = readdirSync(srcDir).filter((f) => f.toLowerCase().endsWith(".svg")).sort();
const used = new Set();
const entries = files.map((file) => {
  const svg = readFileSync(join(srcDir, file), "utf8");
  if (!/xmlns=/.test(svg)) throw new Error(`${file}: add xmlns="http://www.w3.org/2000/svg"`);
  let name = camel(basename(file));
  while (used.has(name)) name += "_";
  used.add(name);
  const [width, height] = sizeOf(svg, file);
  return { name, file, width, height, src: toDataUri(svg) };
});

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(
  outFile,
  `// AUTO-GENERATED by scripts/build-art.mjs from /stickers. Do not edit by hand.
import type { StickerArt } from "../types";

${entries.map((e) => `export const ${e.name}: StickerArt = { name: ${JSON.stringify(e.name)}, width: ${e.width}, height: ${e.height}, src: ${JSON.stringify(e.src)} };`).join("\n")}

/** Every built-in sticker, keyed by name. Importing this pulls in all of them. */
export const allStickers = { ${entries.map((e) => e.name).join(", ")} };
export type StickerName = keyof typeof allStickers;
`
);
console.log(`build-art: ${entries.length} stickers -> src/art/index.ts (${entries.map((e) => e.name).join(", ")})`);
